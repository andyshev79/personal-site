// ── Engine ────────────────────────────────────────────────────────────────────
const DEFAULT_LANG = "uk";

function getLang() {
  return localStorage.getItem("lang") || DEFAULT_LANG;
}

function t(key) {
  const lang = getLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) ||
         (TRANSLATIONS[DEFAULT_LANG] && TRANSLATIONS[DEFAULT_LANG][key]) ||
         key;
}

function applyLang(lang) {
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const text = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) ||
                 (TRANSLATIONS[DEFAULT_LANG] && TRANSLATIONS[DEFAULT_LANG][key]) ||
                 key;
    // Use innerHTML for keys that contain HTML tags
    if (key === "about.h2") {
      el.innerHTML = text;
    } else {
      el.textContent = text;
    }
  });

  // Update lang switcher buttons
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // Re-render posts with updated empty state text
  if (typeof renderPosts === "function" && typeof currentSource !== "undefined") {
    renderPosts(currentSource);
  }
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang(getLang());

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });
});
